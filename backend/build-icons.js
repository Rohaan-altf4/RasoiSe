// Builds frontend/js/icons.js: only the Lucide icons this site uses (about 15 KB instead of the
// 358 KB full library), with the same createIcons() the pages already call.
// Every quoted kebab-case word in the frontend code that is a Lucide icon name is included, so
// icons picked in code (status badges, buttons...) are covered too.
// After using a new icon:  npm run build:icons

const fs = require('fs');
const path = require('path');
const { icons } = require('lucide');
const version = require('lucide/package.json').version;

const FRONTEND = path.join(__dirname, '..', 'frontend');
const files = [];
(function walk(dir) {
  for (const f of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, f.name);
    if (f.isDirectory()) { if (!['uploads', 'i18n'].includes(f.name)) walk(p); } else if (/\.(js|html)$/.test(f.name) && f.name !== 'icons.js') files.push(p);
  }
})(FRONTEND);

const toPascal = s => s.replace(/(\w)(\w*)(_|-|\s*)/g, (g0, g1, g2) => g1.toUpperCase() + g2.toLowerCase());
const used = {};
for (const file of files) {
  const src = fs.readFileSync(file, 'utf8');
  for (const m of src.matchAll(/['"`]([a-z][a-z0-9]*(?:-[a-z0-9]+)*)['"`]/g)) {
    const node = icons[toPascal(m[1])];
    if (node) used[m[1]] = node[2]; // keep only the shapes; the <svg> attributes are the same for all
  }
}

const out = `// Generated by backend/build-icons.js from lucide ${version} (ISC licence). Do not edit by hand.
// ${Object.keys(used).length} icons used by RasoiSe. Same API as the Lucide library: lucide.createIcons().
(function () {
  const ICONS = ${JSON.stringify(used)};
  const SVG = { xmlns: 'http://www.w3.org/2000/svg', width: 24, height: 24, viewBox: '0 0 24 24', fill: 'none', stroke: 'currentColor', 'stroke-width': 2, 'stroke-linecap': 'round', 'stroke-linejoin': 'round' };

  function el(tag, attrs, children) {
    const node = document.createElementNS('http://www.w3.org/2000/svg', tag);
    Object.keys(attrs).forEach(k => node.setAttribute(k, String(attrs[k])));
    (children || []).forEach(([t, a]) => node.appendChild(el(t, a)));
    return node;
  }

  // Swap every <i data-lucide="name"> for its <svg>, keeping the element's own attributes and classes
  function createIcons({ attrs = {} } = {}) {
    document.querySelectorAll('[data-lucide]').forEach(element => {
      if (element.namespaceURI === 'http://www.w3.org/2000/svg') return; // already drawn
      const name = element.getAttribute('data-lucide');
      const shapes = ICONS[name];
      if (!shapes) { console.warn('Icon "' + name + '" is not in js/icons.js. Run: npm run build:icons'); return; }
      const own = {};
      Array.from(element.attributes).forEach(a => { own[a.name] = a.value; });
      const classes = ['lucide', 'lucide-' + name].concat(String(attrs.class || '').split(' '), String(own.class || '').split(' '))
        .map(c => c.trim()).filter((c, i, all) => c && all.indexOf(c) === i).join(' ');
      const svg = el('svg', Object.assign({}, SVG, { 'data-lucide': name }, attrs, own, { class: classes }), shapes);
      if (element.parentNode) element.parentNode.replaceChild(svg, element);
    });
  }

  window.lucide = { createIcons };
})();
`;
fs.writeFileSync(path.join(FRONTEND, 'js', 'icons.js'), out);
console.log(`Wrote frontend/js/icons.js: ${Object.keys(used).length} icons, ${(out.length / 1024).toFixed(1)} KB`);
